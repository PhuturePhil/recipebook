export const PLAN_LANGUAGES = Object.keys(TEXTS)

export function planLanguage() {
  const lang = globalThis.document?.documentElement?.lang ?? 'de'
  return lang.toLowerCase().startsWith('en') ? 'en' : 'de'
}

export function planText(key, params = {}, lang = planLanguage()) {
  const text = TEXTS[lang]?.[key] ?? TEXTS.de[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''))
}

export const planTextKeys = (lang) => Object.keys(TEXTS[lang] ?? {})
